const test = require('node:test'), assert = require('node:assert/strict'), fs = require('node:fs')
const { randomUUID } = require('node:crypto')
const { posDatabase } = require('./helpers/pos-database.cjs')
const { loadTypeScript } = require('./helpers/load-typescript.cjs')
test('retry keys survive failures and reloads; different orders get new keys', () => {
  const { pendingOrder } = loadTypeScript('lib/order-request.ts'), values = new Map()
  const storage = { getItem: key => values.get(key), setItem: (key,value) => values.set(key,value) }
  const draft = { slug:'cafe',customerName:'Guest',phone:'',note:'',items:[{dishId:randomUUID(),quantity:2}] }
  const first=pendingOrder(storage,draft)
  assert.equal(pendingOrder(storage,draft).key,first.key)
  assert.equal(pendingOrder(null,draft,first).key,first.key)
  assert.notEqual(pendingOrder(storage,{...draft,note:'Another order'}).key,first.key)
})
test('orders are atomic, tenant-scoped, retry-safe and status changes are audited', async t => {
  const h=await posDatabase(); t.after(()=>h.db.close())
  await h.db.exec('reset role')
  await h.db.exec(fs.readFileSync('supabase/phase-order-reliability.sql','utf8'))
  await h.as(h.owner)
  await h.ownerAction('settings',h.settings)
  await h.db.exec('reset role'); await h.db.query("update restaurants set menu_mode='ordering' where id=$1",[h.restaurant])
  const submit=async(key=randomUUID(),quantity=2,dish=h.dish)=>{
    await h.as(null,'service_role')
    return (await h.db.query('select orders_submit($1,$2,$3,$4,$5,$6::jsonb) result',['green-bistro',key,'Guest','','',JSON.stringify([{dishId:dish,quantity}])])).rows[0].result
  }
  const key=randomUUID(), first=await submit(key)
  await h.as(h.owner)
  const order=(await h.db.query('select * from orders where idempotency_key=$1',[key])).rows[0]
  assert.equal(Number(order.total),236)
  assert.equal((await h.db.query('select * from order_items where order_id=$1',[order.id])).rows.length,1)
  assert.equal((await h.db.query('select * from pos_kitchen where order_id=$1',[order.id])).rows.length,1)
  const replay=await submit(key); assert.equal(replay.public_token,first.public_token); assert.equal(replay.duplicate,true)
  const concurrent=await Promise.all([submit(key),submit(key)])
  assert.equal(concurrent[0].public_token,concurrent[1].public_token)
  await assert.rejects(()=>submit(key,1),/different order/)
  await assert.rejects(()=>submit(randomUUID(),1,h.otherDish),/no longer available/)
  await assert.rejects(()=>submit(randomUUID(),100),/Invalid order item/)
  await h.db.exec(`reset role; create function test_item_failure() returns trigger language plpgsql as $$ begin raise exception 'Injected item failure'; end $$; create trigger fail_item before insert on order_items for each row execute function test_item_failure();`)
  const failedKey=randomUUID(); await assert.rejects(()=>submit(failedKey),/Injected item failure/)
  await h.db.exec('reset role; drop trigger fail_item on order_items; drop function test_item_failure();')
  assert.equal((await h.db.query('select * from orders where idempotency_key=$1',[failedKey])).rows.length,0)
  await h.db.query("update restaurants set menu_mode='view_only' where id=$1",[h.restaurant])
  assert.equal((await submit(key)).public_token,first.public_token)
  await assert.rejects(()=>submit(),/takes orders verbally/)
  await h.as(h.otherOwner); await assert.rejects(()=>h.db.query("select orders_change($1,$2,0,'confirmed','')",[h.restaurant,order.id]),/access denied/)
  await h.as(h.owner)
  await assert.rejects(()=>h.db.query("select orders_change($1,$2,0,'completed','')",[h.restaurant,order.id]),/not allowed/)
  const changed=(await h.db.query("select orders_change($1,$2,0,'confirmed','') result",[h.restaurant,order.id])).rows[0].result
  assert.equal(changed.version,1); assert.equal(changed.order_items.length,1)
  await assert.rejects(()=>h.db.query("select orders_change($1,$2,0,'preparing','')",[h.restaurant,order.id]),/order changed/)
  await assert.rejects(()=>h.db.query("select orders_change($1,$2,1,'cancelled','')",[h.restaurant,order.id]),/reason/)
  await h.db.query("select orders_change($1,$2,1,'cancelled','Guest cancelled')",[h.restaurant,order.id])
  assert.equal((await h.db.query('select reason from order_events where order_id=$1 order by created_at desc limit 1',[order.id])).rows[0].reason,'Guest cancelled')
  assert.equal((await h.db.query('select state from pos_kitchen where order_id=$1',[order.id])).rows[0].state,'cancelled')
  await h.as(null); await assert.rejects(()=>h.db.query("select orders_submit('green-bistro',$1,'Guest','','','[]')",[randomUUID()]),/permission denied/)
})
