const test=require('node:test'),assert=require('node:assert/strict'),{randomUUID}=require('node:crypto')
const {posDatabase}=require('./helpers/pos-database.cjs'),{paymentFixture}=require('./helpers/payment-fixture.cjs')
test('provider HTTP protocol recovers ambiguous orders/refunds and rejects forged, mismatched and repeated payments',async t=>{
  const h=await posDatabase();const f=await paymentFixture(h);t.after(async()=>{await f.close();await h.db.close()})
  await h.as(h.owner);await h.ownerAction('settings',h.settings)
  const oid=await h.order();await h.as(h.owner);const bill=await h.ownerAction('issue',{order_ids:[oid],request_key:randomUUID()})
  f.loseNextOrder();const key=randomUUID(),lost=await f.checkout(bill.public_token,key);assert.equal(lost.response.status,503)
  const recovered=await f.checkout(bill.public_token,key);assert.equal(recovered.response.status,200)
  assert.equal(f.calls.filter(c=>c.method==='POST'&&c.path==='/v1/orders').length,1)
  assert.ok(f.calls.some(c=>c.method==='GET'&&c.query.includes('receipt=')))
  const c=recovered.data,p=f.payment(c.orderId,{status:'authorized',captured:false})
  const verify=async(payment=p,signature=payment.signature)=>f.api.verify.POST(f.request('/api/public/billing/verify',{token:bill.public_token,checkoutId:c.checkoutId,paymentId:payment.id,signature}))
  assert.equal((await verify(p,'0'.repeat(64))).status,400)
  assert.equal((await verify()).status,202)
  for(const change of [{amount:1},{currency:'USD'},{order_id:'order_wrong'}]) {
    f.payments.set(p.id,{...p,status:'captured',captured:true,...change});assert.equal((await verify()).status,202)
  }
  f.payments.set(p.id,{...p,status:'captured',captured:true});assert.equal((await verify()).status,200)
  assert.equal((await verify()).status,200)
  assert.equal((await f.webhook('payment.captured',{...p,status:'captured',captured:true},false)).status,400)
  assert.equal((await f.webhook('payment.captured',{...p,status:'captured',captured:true})).status,200)
  await h.as(h.owner);let state=await h.ownerAction('state',{bill_id:bill.id});assert.equal(state.payments.length,1);assert.equal(Number(state.balance_paise),0)
  const refundKey=randomUUID(),body={action:'refund',data:{payment_id:state.payments[0].id,amount_paise:1800,reason:'Item returned',request_key:refundKey}}
  f.loseNextRefund();assert.equal((await f.api.billing.POST(f.request('/api/billing',body))).status,202)
  assert.equal((await f.api.billing.POST(f.request('/api/billing',body))).status,200)
  assert.equal(f.calls.filter(c=>c.method==='POST'&&c.path.endsWith('/refund')).length,1)
  const refund=[...f.refunds.values()][0];assert.equal((await f.webhook('refund.processed',refund)).status,200)
  assert.equal((await f.webhook('refund.created',{...refund,status:'pending'})).status,200)
  await h.as(h.owner);state=await h.ownerAction('state',{bill_id:bill.id});assert.equal(state.refunds.length,1);assert.equal(state.refunds[0].state,'processed');assert.equal(state.credits.length,1);assert.equal(Number(state.credited_paise),1800)
  // A new bill covers a definitively rejected order.
  const next=await h.ownerAction('issue',{items:[{dish_id:h.dish,quantity:1}],request_key:randomUUID()})
  f.rejectNextOrder(400);assert.equal((await f.checkout(next.public_token)).response.status,503)
  const retry=await f.checkout(next.public_token);assert.equal(retry.response.status,200)
  const second=f.payment(retry.data.orderId)
  assert.equal((await f.webhook('payment.captured',second)).status,200)
  const wrong={...second,id:'pay_wrongAmount',amount:1};assert.equal((await f.webhook('payment.captured',wrong)).status,503)
  await h.as(h.owner)
  const earlyBill=await h.ownerAction('issue',{items:[{dish_id:h.dish,quantity:1}],request_key:randomUUID()})
  const reserved=await h.gateway('checkout',{token:earlyBill.public_token,request_key:randomUUID(),account_key_id:f.account.keyId})
  const earlyOrder={id:'order_early',amount:11800,currency:'INR',receipt:reserved.id,notes:{pos_checkout_id:reserved.id}}
  f.orders.set(earlyOrder.id,earlyOrder);const early=f.payment(earlyOrder.id)
  assert.equal((await f.webhook('payment.captured',early)).status,503)
  assert.equal((await f.checkout(earlyBill.public_token)).response.status,200)
  assert.equal((await f.webhook('payment.captured',early)).status,200)
})
